import type { Metadata } from "next";

/** Canonical origin (the apex domain redirects here). */
export const SITE_URL = "https://www.hexaapps.net";
export const SITE_NAME = "Hexa Apps";
export const SITE_DESCRIPTION =
  "Hexa Apps is an independent studio making small apps with care: cozy mobile games like Trim & Tend, focused iOS and Android utilities, and web tools.";
export const CONTACT_EMAIL = "hexagameapps@gmail.com";

type PageSeo = {
  /** Page title; the root layout appends "| Hexa Apps". */
  title: string;
  description: string;
  /** Path starting with "/", used for the canonical URL. */
  path: string;
  /** Absolute or root-relative image URL for social previews. */
  image?: string;
  imageAlt?: string;
};

/** Builds consistent title, description, canonical and social tags for a page. */
export function pageMetadata({ title, description, path, image, imageAlt }: PageSeo): Metadata {
  // Page-level openGraph replaces the parent's, so always name an image:
  // the page's own, or the branded one generated by app/opengraph-image.tsx.
  const images = [
    image
      ? { url: image, alt: imageAlt ?? title }
      : { url: "/opengraph-image", width: 1200, height: 630, alt: `${SITE_NAME} — Small apps, made with care.` },
  ];
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: "en_US",
      url: path,
      title: `${title} | ${SITE_NAME}`,
      description,
      images,
    },
    twitter: {
      card: "summary_large_image",
      title: `${title} | ${SITE_NAME}`,
      description,
      images,
    },
  };
}
